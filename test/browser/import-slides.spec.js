import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { pdfFixture, pptxFixture } from '../document-fixtures.js';
async function upload(page, name, buffer) {
  await page.getByRole('button', { name: '↑ Importar slides', exact: true }).click();
  await page.locator('#import-slides-file').setInputFiles({ name, mimeType: name.endsWith('.pdf') ? 'application/pdf' : 'application/vnd.openxmlformats-officedocument.presentationml.presentation', buffer });
  await expect(page.getByLabel('Título da aula', { exact: true })).toBeVisible({ timeout: 60000 });
}
test('PDF vira páginas persistidas, apresenta em tela cheia e sincroniza com celular e reconexão do professor', async ({ browser }) => {
  const hostContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const host = await hostContext.newPage(), phone = await phoneContext.newPage(), errors = [];
  for (const page of [host, phone]) page.on('pageerror', e => errors.push(e.message));
  await host.goto('/?localSignal');
  await upload(host, 'slides-do-professor.pdf', pdfFixture());
  await expect(host.locator('.outline-item')).toHaveCount(2);
  await expect(host.locator('.imported-page-preview img')).toHaveJSProperty('naturalWidth', 1920);
  await host.getByRole('button', { name: 'Apresentar ↗', exact: true }).click();
  await expect(host.getByRole('dialog')).toBeVisible();
  const code = (await host.locator('.big-code').innerText()).replace(/\s/g, '');
  await host.getByRole('button', { name: 'Fechar convite', exact: true }).click();
  await expect(host.locator('.document-stage img')).toBeVisible();
  await host.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  await expect.poll(() => host.evaluate(() => Boolean(document.fullscreenElement))).toBe(true);
  await host.screenshot({ path: 'test-results/imported-pdf-fullscreen.png' });
  await host.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  await phone.goto('/?localSignal&s=' + code);
  await phone.getByLabel('Como podemos chamar você?', { exact: true }).fill('Ana PDF');
  await phone.getByRole('button', { name: 'Entrar na sala', exact: true }).click();
  await expect(phone.locator('.document-stage img')).toHaveJSProperty('naturalWidth', 1920);
  const first = await phone.locator('.document-stage img').getAttribute('src');
  await host.getByRole('button', { name: 'Próximo', exact: true }).click();
  await expect(phone.locator('.document-nav .slide-counter')).toContainText('2 / 2');
  expect(await phone.locator('.document-stage img').getAttribute('src')).not.toBe(first);
  await host.reload();
  await expect(host.locator('#document-page')).toHaveValue('1', { timeout: 30000 });
  await host.getByLabel('Ir para página', { exact: true }).selectOption('0');
  await expect(phone.locator('.document-nav .slide-counter')).toContainText('1 / 2', { timeout: 30000 });
  await phone.screenshot({ path: 'test-results/imported-pdf-phone.png', fullPage: true });
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await phoneContext.close(); await hostContext.close();
});
test('PPTX mantém páginas, exporta JSON portátil e reabre imagens em outro navegador', async ({ page, browser }) => {
  await page.goto('/');
  await upload(page, 'minha-apresentacao.pptx', await pptxFixture());
  await expect(page.locator('.outline-item')).toHaveCount(2);
  await expect(page.locator('.imported-notice')).toContainText('animações e vídeos não são importados');
  await expect(page.locator('.imported-page-preview img')).toHaveJSProperty('naturalWidth', 1920);
  const downloaded = page.waitForEvent('download');
  await page.locator('[data-studio-action="export-draft"]').click();
  const download = await downloaded;
  const json = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(json.slides).toHaveLength(2);
  expect(json.slides[0].image).toMatch(/^data:image\/jpeg/);
  expect(json.slides[0].assetId).toBeUndefined();
  await page.getByRole('button', { name: '▷ Prévia', exact: true }).click();
  await expect(page.locator('.document-stage img')).toBeVisible();
  await page.screenshot({ path: 'test-results/imported-pptx.png', fullPage: true });
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.reload();
  await page.locator('.lesson-card').first().locator('[data-studio-action="preview"]').click();
  await expect(page.locator('.document-stage img')).toHaveJSProperty('naturalWidth', 1920);
  const context = await browser.newContext(), other = await context.newPage();
  await other.goto('/');
  await other.locator('#import-lesson-file').setInputFiles({ name: 'aula.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(json)) });
  await expect(other.getByLabel('Título da aula', { exact: true })).toHaveValue('minha-apresentacao');
  await other.getByRole('button', { name: '▷ Prévia', exact: true }).click();
  await expect(other.locator('.document-stage img')).toHaveJSProperty('naturalWidth', 1920);
  await other.getByRole('button', { name: 'Próximo', exact: true }).click();
  await expect(other.locator('.document-nav .slide-counter')).toContainText('2 / 2');
  await context.close();
});
test('PDF importa no build do GitHub Pages; arquivos inválidos, excesso de páginas e cancelamento preservam a biblioteca', async ({ page }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/senaidendezas/');
  await upload(page, 'no-github-pages.pdf', pdfFixture());
  await page.getByRole('button', { name: '▷ Prévia', exact: true }).click();
  await expect(page.locator('.document-stage img')).toHaveJSProperty('naturalWidth', 1920);
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.locator('.editor-heading [data-studio-action="library"]').click();
  const count = await page.locator('.lesson-card').count();
  await page.getByRole('button', { name: '↑ Importar slides', exact: true }).click();
  await page.locator('#import-slides-file').setInputFiles({ name: 'invalido.pdf', mimeType: 'application/pdf', buffer: Buffer.from('arquivo inválido') });
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('PDF válido');
  await expect(page.locator('.lesson-card')).toHaveCount(count);
  await page.getByRole('dialog').getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByRole('button', { name: '↑ Importar slides', exact: true }).click();
  await page.locator('#import-slides-file').setInputFiles({ name: 'muitas-paginas.pdf', mimeType: 'application/pdf', buffer: pdfFixture(81) });
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('1 a 80');
  await page.getByRole('dialog').getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByRole('button', { name: '↑ Importar slides', exact: true }).click();
  await page.locator('#import-slides-file').setInputFiles({ name: 'cancelar.pdf', mimeType: 'application/pdf', buffer: pdfFixture(30) });
  await page.getByRole('button', { name: 'Cancelar importação', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.lesson-card')).toHaveCount(count);
  expect(errors).toEqual([]);
});
