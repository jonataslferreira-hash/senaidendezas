import { test, expect } from '@playwright/test';
import { newLesson } from '../../src/lessons.js';

test('modelo atual fica bloqueado para o aluno; tela cheia mostra controles por movimento, QR nos quatro cantos e edição ao vivo', async ({ browser }) => {
  const hostContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const host = await hostContext.newPage(), phone = await phoneContext.newPage(), errors = [];
  for (const page of [host, phone]) page.on('pageerror', error => errors.push(error.message));
  await host.goto('/?localSignal');
  await host.locator('[data-studio-action="present"]').click();
  await expect(host.getByRole('dialog')).toBeVisible();
  const code = (await host.locator('.big-code').innerText()).replace(/\s/g, '');
  await host.getByRole('button', { name: 'Fechar convite', exact: true }).click();
  await phone.goto('/?localSignal&s=' + code);
  await phone.getByLabel('Como podemos chamar você?', { exact: true }).fill('Ana');
  await phone.getByRole('button', { name: 'Entrar na sala', exact: true }).click();
  await expect(phone.getByRole('button', { name: 'HDD', exact: true })).toBeDisabled();
  await expect(phone.getByRole('button', { name: 'SSD NVMe', exact: true })).toBeDisabled();
  await host.getByRole('button', { name: 'Próximo', exact: true }).click();
  await expect(phone.getByRole('button', { name: 'HDD', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(phone.getByRole('button', { name: 'SSD SATA', exact: true })).toBeDisabled();
  await host.getByLabel('QR Code', { exact: true }).check();
  await host.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  await expect(host.locator('#app')).toHaveClass(/is-presenting/);
  await expect(host.locator('.pinned-room-qr img')).toHaveAttribute('src', /^data:image/);
  await expect(host.locator('.pinned-room-qr strong')).toContainText(code.slice(0, 3) + ' ' + code.slice(3));
  for (const corner of ['tl', 'tr', 'bl', 'br']) {
    await host.mouse.move(720, 120);
    await host.getByLabel('Canto do QR Code', { exact: true }).selectOption(corner);
    const box = await host.locator('.pinned-room-qr').boundingBox();
    expect(corner.endsWith('l') ? box.x : 1440 - box.x - box.width).toBeCloseTo(16, 0);
    expect(corner.startsWith('t') ? box.y : 1000 - box.y - box.height).toBeCloseTo(16, 0);
  }
  await host.locator('.slide-panel h1').click();
  await host.mouse.move(700, 500);
  await expect(host.locator('.presentation-toolbar')).toHaveCSS('opacity', '0', { timeout: 6000 });
  await host.mouse.move(710, 510);
  await expect(host.locator('.presentation-toolbar')).toHaveCSS('opacity', '1');
  await host.getByRole('button', { name: '✎ Editar slide', exact: true }).click();
  await host.getByLabel('Título do slide', { exact: true }).fill('HDD explorado em tela cheia');
  await host.getByLabel('Notas só para o professor', { exact: true }).fill('ANOTAÇÃO PRIVADA DO PROFESSOR');
  await host.getByRole('button', { name: 'Salvar slide', exact: true }).click();
  await expect(phone.getByRole('heading', { name: 'HDD explorado em tela cheia', exact: true })).toBeVisible();
  await expect(phone.locator('body')).not.toContainText('ANOTAÇÃO PRIVADA DO PROFESSOR');
  await host.mouse.move(700, 500);
  await host.screenshot({ path: 'test-results/native-model-fullscreen.png' });
  await host.mouse.move(710, 510);
  await host.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  await host.getByRole('button', { name: 'Sair', exact: true }).click();
  await host.reload();
  await host.locator('[data-studio-action="edit"]').click();
  await host.getByRole('button', { name: 'Campos', exact: true }).click();
  await host.locator('.outline-item').nth(1).click();
  await expect(host.getByLabel('Título do slide', { exact: true })).toHaveValue('HDD explorado em tela cheia');
  expect(errors).toEqual([]);
  await phoneContext.close(); await hostContext.close();
});

test('slide de imagem do editor ocupa a tela inteira; texto pode ser mostrado, editado e navegado sem sair da tela cheia', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  const image = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 1600; canvas.height = 900;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#153b37'; ctx.fillRect(0, 0, 1600, 900);
    ctx.fillStyle = '#a8dfcc'; ctx.font = 'bold 74px Arial'; ctx.fillText('Uma imagem criada no site', 120, 350);
    ctx.fillStyle = '#fff'; ctx.font = '36px Arial'; ctx.fillText('O conteúdo ocupa o palco inteiro.', 120, 450);
    return canvas.toDataURL('image/png');
  });
  const lesson = newLesson();
  lesson.title = 'Uma aula em tela cheia';
  lesson.slides[0] = { ...lesson.slides[0], kind: 'image', title: 'Um slide de imagem', intro: 'Uma explicação sobre esta imagem.', image, imageAlt: 'Imagem didática em verde' };
  lesson.slides.push({ ...lesson.slides[0], id: 'text-slide', kind: 'text', title: 'Os três estados da água', points: ['Sólido', 'Líquido', 'Gasoso'], image: '' });
  await page.locator('#import-lesson-file').setInputFiles({ name: 'aula.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(lesson)) });
  await expect(page.getByLabel('Título da aula', { exact: true })).toHaveValue(lesson.title);
  await page.getByRole('button', { name: '▷ Prévia', exact: true }).click();
  await page.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  const box = await page.locator('.lesson-image img').boundingBox();
  expect(box.x).toBe(0); expect(box.y).toBe(0); expect(box.width).toBe(1440); expect(box.height).toBe(1000);
  await expect(page.locator('.slide-panel')).toBeHidden();
  await page.getByRole('button', { name: 'Mostrar texto', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Um slide de imagem', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '✎ Editar slide', exact: true }).click();
  await page.getByLabel('Título do slide', { exact: true }).fill('Imagem atualizada');
  await page.getByRole('button', { name: 'Salvar slide', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Imagem atualizada', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Avançar slide', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Os três estados da água', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  await page.screenshot({ path: 'test-results/native-text-fullscreen.png' });
  await page.getByRole('button', { name: 'Apresentar em tela cheia', exact: true }).click();
  await expect(page.locator('#app')).not.toHaveClass(/is-presenting/);
});
