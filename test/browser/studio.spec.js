test('aula personalizada chega a um celular sem biblioteca local, com imagem e quiz próprios', async ({ browser }) => {
  const hostContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const host = await hostContext.newPage(), phone = await phoneContext.newPage(), failures = [];
  for (const page of [host, phone]) page.on('pageerror', error => failures.push(error.message));
  const lesson = newLesson();
  lesson.title = 'A água em movimento'; lesson.slides[0].title = 'O caminho da chuva'; lesson.slides[0].intro = 'Uma aula de ciências.'; lesson.slides[0].note = 'SEGREDO DO PROFESSOR';
  lesson.slides.push({ ...lesson.slides[0], id: 'image-slide', kind: 'image', title: 'Observe a imagem', image, imageAlt: 'Uma gota ilustrativa' });
  lesson.questions = [{ ...newQuestion(), text: 'Qual é a resposta?', options: ['Incorreto', 'Correto'], correct: 1, seconds: 60, difficulty: 'Difícil', explanation: 'Esta é a explicação da aula personalizada.' }];
  await host.goto('/?localSignal');
  await importLesson(host, lesson);
  await host.getByRole('button', { name: 'Apresentar ↗', exact: true }).click();
  await expect(host.getByRole('dialog')).toBeVisible();
  const code = (await host.locator('.big-code').innerText()).replace(/\s/g, '');
  await host.getByRole('button', { name: 'Fechar convite', exact: true }).click();
  await phone.goto('/?localSignal&s=' + code);
  await phone.getByLabel('Como podemos chamar você?', { exact: true }).fill('Bia');
  await phone.getByRole('button', { name: 'Entrar na sala', exact: true }).click();
  await expect(phone.getByRole('heading', { name: 'O caminho da chuva', exact: true })).toBeVisible();
  await expect(phone.locator('body')).not.toContainText('SEGREDO DO PROFESSOR');
  await expect(phone.locator('canvas')).toHaveCount(0);
  await host.getByRole('button', { name: 'Próximo', exact: true }).click();
  await expect(phone.getByRole('heading', { name: 'Observe a imagem', exact: true })).toBeVisible();
  await expect(phone.getByRole('img', { name: 'Uma gota ilustrativa', exact: true })).toBeVisible();
  expect(await phone.getByRole('img', { name: 'Uma gota ilustrativa', exact: true }).evaluate(img => img.naturalWidth)).toBeGreaterThan(0);
  await phone.reload();
  await expect(phone.getByRole('heading', { name: 'Observe a imagem', exact: true })).toBeVisible();
  await host.clock.setFixedTime(new Date());
  await host.getByRole('button', { name: 'Iniciar quiz', exact: true }).click();
  await expect(phone.locator('.quiz-lobby')).toBeVisible();
  await host.getByRole('button', { name: 'Começar quiz', exact: false }).click();
  await expect(phone.locator('.question-card')).toContainText('Qual é a resposta?');
  await expect(phone.locator('.question-meta')).toContainText('2.000');
  await phone.locator('[data-answer="1"]').click();
  await expect(phone.locator('.answer-status')).toContainText('Resposta registrada');
  await host.getByRole('button', { name: 'Revelar resposta', exact: true }).click();
  await expect(phone.locator('.answer-explanation')).toContainText('Esta é a explicação da aula personalizada.');
  await host.getByRole('button', { name: 'Ver resultado', exact: true }).click();
  await expect(phone.locator('.place-1')).toContainText('Bia');
  await expect(host.locator('.full-ranking')).toContainText('1 acerto');
  expect(failures).toEqual([]);
  await phoneContext.close(); await hostContext.close();
});

